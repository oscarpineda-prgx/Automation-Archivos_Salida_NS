def sanitize_folder_name(text: str) -> str:
    """Reemplaza caracteres no permitidos en nombres de carpeta."""
    invalid = '<>:"/\\|?*'
    return "".join("_" if ch in invalid else ch for ch in str(text)).strip()


def create_provider_folders(proveedores=PROVEEDORES, output_root=OUTPUT_ROOT):
    """Crea carpetas por proveedor y las subcarpetas requeridas."""
    base = Path(output_root)
    base.mkdir(parents=True, exist_ok=True)

    for numero, nombre in proveedores:
        folder_name = f"{numero} - {nombre}"
        proveedor_dir = base / sanitize_folder_name(folder_name)
        proveedor_dir.mkdir(parents=True, exist_ok=True)

        for sub in SUBFOLDERS:
            (proveedor_dir / sanitize_folder_name(sub)).mkdir(parents=True, exist_ok=True)

    print(f"Carpetas creadas en: {base}")


if __name__ == "__main__":
    create_provider_folders()
